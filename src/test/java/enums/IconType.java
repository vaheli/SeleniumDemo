package enums;

/**
 * Перечисление типов иконок ошибок для тестов авторизации.
 * Используется для определения, какая иконка ошибки должна отображаться при неверных учетных данных.
 */
public enum IconType {
    /**
     * Иконка ошибки для поля имени пользователя.
     */
    USERNAME,

    /**
     * Иконка ошибки для поля пароля.
     */
    PASSWORD,

    /**
     * Обе иконки ошибки (для имени пользователя и пароля).
     */
    BOTH,

    /**
     * Нет иконок ошибки.
     */
    NONE
}
